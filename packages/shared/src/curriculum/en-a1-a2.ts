import type { CefrLevel, Exercise, Lesson, SkillDimension, Unit } from '../types.js';

interface LessonBlueprint {
  id: string;
  titlePt: string;
  subtitlePt: string;
  focusSkill: SkillDimension;
  durationMinutes?: number;
  xpReward?: number;
  choice: {
    type?: 'context_choice' | 'trap_buster' | 'dialogue_complete';
    promptPt: string;
    contextSituationPt?: string;
    targetText: string;
    ipa: string;
    translationPt: string;
    tipPt: string;
    options: Array<{ id: string; text: string; translationPt?: string }>;
    correctOptionId: string;
    dialogueLines?: Array<{ speaker: string; text: string; translationPt: string; isBlank?: boolean }>;
  };
  build: {
    promptPt: string;
    targetText: string;
    ipa: string;
    translationPt: string;
    tipPt: string;
    tokens: string[];
    distractors: string[];
  };
  speak: {
    promptPt: string;
    contextSituationPt?: string;
    targetText: string;
    ipa: string;
    translationPt: string;
    tipPt: string;
    variants?: string[];
  };
  pairs?: {
    promptPt: string;
    tipPt: string;
    items: Array<{ id: string; left: string; right: string; emoji?: string }>;
  };
}

interface UnitBlueprint {
  id: string;
  cefr: CefrLevel;
  titlePt: string;
  descriptionPt: string;
  culturalNotePt: string;
  grammarFocusPt: string;
  lessons: LessonBlueprint[];
}

export function compileEnglishUnits(blueprints: UnitBlueprint[]): Unit[] {
  return blueprints.map((u, uIdx) => ({
    id: u.id,
    language: 'en',
    order: uIdx + 1,
    cefr: u.cefr,
    titlePt: u.titlePt,
    descriptionPt: u.descriptionPt,
    culturalNotePt: u.culturalNotePt,
    grammarFocusPt: u.grammarFocusPt,
    lessons: u.lessons.map((l, lIdx): Lesson => {
      const exercises: Exercise[] = [
        {
          id: `${l.id}-e1`,
          type: l.choice.type ?? 'context_choice',
          skill: l.choice.type === 'trap_buster' ? 'vocabulary' : 'reading',
          promptPt: l.choice.promptPt,
          contextSituationPt: l.choice.contextSituationPt,
          targetText: l.choice.targetText,
          ipaOrPhoneticBr: l.choice.ipa,
          translationPt: l.choice.translationPt,
          brazilianTipPt: l.choice.tipPt,
          options: l.choice.options,
          correctOptionId: l.choice.correctOptionId,
          dialogueLines: l.choice.dialogueLines,
        },
        {
          id: `${l.id}-e2`,
          type: 'listen_build',
          skill: 'listening',
          promptPt: l.build.promptPt,
          targetText: l.build.targetText,
          ipaOrPhoneticBr: l.build.ipa,
          translationPt: l.build.translationPt,
          brazilianTipPt: l.build.tipPt,
          wordBank: [...l.build.tokens, ...l.build.distractors],
          correctTokens: l.build.tokens,
        },
        {
          id: `${l.id}-e3`,
          type: 'speak_pronounce',
          skill: 'speaking',
          promptPt: l.speak.promptPt,
          contextSituationPt: l.speak.contextSituationPt,
          targetText: l.speak.targetText,
          ipaOrPhoneticBr: l.speak.ipa,
          translationPt: l.speak.translationPt,
          brazilianTipPt: l.speak.tipPt,
          acceptedSpeechVariants: l.speak.variants,
        },
      ];

      if (l.pairs) {
        exercises.splice(1, 0, {
          id: `${l.id}-e-pairs`,
          type: 'match_pairs',
          skill: 'vocabulary',
          promptPt: l.pairs.promptPt,
          targetText: l.pairs.items.map((p) => p.left).join(' / '),
          translationPt: l.pairs.items.map((p) => p.right).join(' / '),
          brazilianTipPt: l.pairs.tipPt,
          pairs: l.pairs.items,
        });
      }

      return {
        id: l.id,
        unitId: u.id,
        order: lIdx + 1,
        titlePt: l.titlePt,
        subtitlePt: l.subtitlePt,
        durationMinutes: l.durationMinutes ?? 5,
        xpReward: l.xpReward ?? (u.cefr === 'A1' ? 45 : u.cefr === 'A2' ? 55 : u.cefr === 'B1' ? 65 : u.cefr === 'B2' ? 75 : 85),
        cefr: u.cefr,
        focusSkill: l.focusSkill,
        exercises,
      };
    }),
  }));
}

